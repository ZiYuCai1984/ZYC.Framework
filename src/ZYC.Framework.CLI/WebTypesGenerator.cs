using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using ZYC.Framework.Abstractions.Web;

namespace ZYC.Framework.CLI;

/// <summary>
///     Generates TypeScript declarations for interfaces marked with <see cref="ExposeToWebAttribute" />.
///     The declarations match the JSON that <c>ZYC.Framework.WebView2.WebBridge</c> reads and writes:
///     camelCase names, enums as strings, and a Promise for every call.
/// </summary>
public class WebTypesGenerator
{
    private static readonly HashSet<Type> StringTypes =
    [
        typeof(string), typeof(char), typeof(Guid), typeof(DateTime), typeof(DateTimeOffset),
        typeof(DateOnly), typeof(TimeOnly), typeof(TimeSpan), typeof(Uri), typeof(byte[])
    ];

    private static readonly HashSet<Type> NumberTypes =
    [
        typeof(byte), typeof(sbyte), typeof(short), typeof(ushort), typeof(int), typeof(uint),
        typeof(long), typeof(ulong), typeof(float), typeof(double), typeof(decimal)
    ];

    private readonly NullabilityInfoContext _nullability = new();

    private readonly Queue<Type> _pendingTypes = new();

    private readonly Dictionary<Type, string> _typeNames = new();

    private readonly HashSet<string> _usedNames = new(StringComparer.Ordinal);

    private readonly List<string> _warnings = [];

    public static WebTypesGenerationResult Generate(IReadOnlyList<string> assemblyPaths)
    {
        var assemblies = assemblyPaths
            .Select(path => Assembly.LoadFrom(Path.GetFullPath(path)))
            .ToArray();

        return new WebTypesGenerator().Run(assemblies);
    }

    /// <summary>
    ///     Writes the content with CRLF line endings and no BOM, unless the file already has the same content.
    ///     Leaving an unchanged file alone keeps the front-end build incremental.
    /// </summary>
    public static bool WriteIfChanged(string filePath, string content)
    {
        content = content.Replace("\n", "\r\n", StringComparison.Ordinal);

        if (File.Exists(filePath) && File.ReadAllText(filePath) == content)
        {
            return false;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(filePath)!);
        File.WriteAllText(filePath, content, new UTF8Encoding(false));
        return true;
    }

    private WebTypesGenerationResult Run(IReadOnlyList<Assembly> assemblies)
    {
        var services = new List<(string ServiceName, string TypeName, Type Type)>();
        ReserveName("HostServices");

        foreach (var type in assemblies
                     .SelectMany(GetLoadableTypes)
                     .Where(t => t is { IsInterface: true, IsGenericTypeDefinition: false }
                                 && t.IsDefined(typeof(ExposeToWebAttribute), false))
                     .OrderBy(ExposeToWebAttribute.GetServiceName, StringComparer.Ordinal))
        {
            var serviceName = ExposeToWebAttribute.GetServiceName(type);
            if (services.Any(s => string.Equals(s.ServiceName, serviceName, StringComparison.OrdinalIgnoreCase)))
            {
                AddWarning($"The service name '{serviceName}' of {type.FullName} is already used; it is skipped.");
                continue;
            }

            services.Add((serviceName, ReserveName(ToIdentifier(serviceName)), type));
        }

        var serviceDeclarations = new StringBuilder();
        foreach (var service in services)
        {
            WriteService(serviceDeclarations, service.TypeName, service.Type);
        }

        var typeDeclarations = new StringBuilder();
        while (_pendingTypes.TryDequeue(out var type))
        {
            WriteDataType(typeDeclarations, type);
        }

        var sources = string.Join(", ", assemblies.Select(a => Path.GetFileName(a.Location)));

        var output = new StringBuilder();
        output.Append("// <auto-generated>\n");
        output.Append($"//     Generated by `zyc web-types` from the [ExposeToWeb] interfaces in {sources}.\n");
        output.Append("//     Do not edit: the build regenerates this file when those interfaces change.\n");
        output.Append("// </auto-generated>\n\n");
        output.Append(typeDeclarations);
        output.Append(serviceDeclarations);
        output.Append("/** Maps the service names accepted by hostService() to their types. */\n");
        output.Append("export interface HostServices {\n");
        foreach (var service in services)
        {
            output.Append($"  {ToPropertyKey(service.ServiceName)}: {service.TypeName}\n");
        }

        output.Append("}\n");

        return new WebTypesGenerationResult(output.ToString(), _warnings);
    }

    private void WriteService(StringBuilder builder, string typeName, Type type)
    {
        builder.Append($"export interface {typeName} {{\n");

        var methodGroups = type.GetMethods()
            .Where(m => !m.IsSpecialName && !m.ContainsGenericParameters)
            .GroupBy(m => m.Name, StringComparer.OrdinalIgnoreCase)
            .OrderBy(g => g.Key, StringComparer.Ordinal);

        foreach (var group in methodGroups)
        {
            if (group.Count() > 1)
            {
                AddWarning($"{type.FullName}.{group.Key} is overloaded, which the web bridge does not support; it is skipped.");
                continue;
            }

            var method = group.First();
            try
            {
                var parameters = method.GetParameters()
                    .Where(p => p.ParameterType != typeof(CancellationToken))
                    .Select(p => $"{p.Name}{(p.HasDefaultValue ? "?" : string.Empty)}: " +
                                 MapType(p.ParameterType, _nullability.Create(p)));

                builder.Append(
                    $"  {ToCamelCase(method.Name)}({string.Join(", ", parameters)}): Promise<{MapReturnType(method)}>\n");
            }
            catch (Exception e) when (e is FileNotFoundException or FileLoadException or TypeLoadException)
            {
                AddWarning($"{type.FullName}.{method.Name} is skipped: {e.Message}");
            }
        }

        builder.Append("}\n\n");
    }

    private void WriteDataType(StringBuilder builder, Type type)
    {
        var name = _typeNames[type];

        if (type.IsEnum)
        {
            var members = Enum.GetNames(type).Select(n => $"'{n}'").ToArray();
            builder.Append($"export type {name} = {(members.Length == 0 ? "never" : string.Join(" | ", members))}\n\n");
            return;
        }

        builder.Append($"export interface {name} {{\n");

        foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetMethod is not { IsPublic: true }
                || property.GetIndexParameters().Length > 0
                || property.IsDefined(typeof(JsonIgnoreAttribute), true))
            {
                continue;
            }

            var jsonName = property.GetCustomAttribute<JsonPropertyNameAttribute>(true)?.Name
                           ?? ToCamelCase(property.Name);
            try
            {
                builder.Append(
                    $"  {ToPropertyKey(jsonName)}: {MapType(property.PropertyType, _nullability.Create(property))}\n");
            }
            catch (Exception e) when (e is FileNotFoundException or FileLoadException or TypeLoadException)
            {
                AddWarning($"{type.FullName}.{property.Name} is skipped: {e.Message}");
            }
        }

        builder.Append("}\n\n");
    }

    private string MapReturnType(MethodInfo method)
    {
        var type = method.ReturnType;
        if (type == typeof(void) || type == typeof(Task) || type == typeof(ValueTask))
        {
            return "void";
        }

        var nullability = _nullability.Create(method.ReturnParameter);
        if (type.IsGenericType
            && (type.GetGenericTypeDefinition() == typeof(Task<>)
                || type.GetGenericTypeDefinition() == typeof(ValueTask<>)))
        {
            return MapType(type.GetGenericArguments()[0], GetGenericArgument(nullability, 0));
        }

        return MapType(type, nullability);
    }

    private string MapType(Type type, NullabilityInfo? nullability)
    {
        var underlyingType = Nullable.GetUnderlyingType(type);
        if (underlyingType is not null)
        {
            return $"{MapNonNullableType(underlyingType, null)} | null";
        }

        var mapped = MapNonNullableType(type, nullability);
        return !type.IsValueType && nullability?.ReadState == NullabilityState.Nullable
            ? $"{mapped} | null"
            : mapped;
    }

    private string MapNonNullableType(Type type, NullabilityInfo? nullability)
    {
        if (StringTypes.Contains(type))
        {
            return "string";
        }

        if (type == typeof(bool))
        {
            return "boolean";
        }

        if (NumberTypes.Contains(type))
        {
            return "number";
        }

        if (type.IsEnum)
        {
            return DeclareType(type);
        }

        if (type == typeof(object) || type.Namespace is "System.Text.Json" or "System.Text.Json.Nodes")
        {
            return "unknown";
        }

        if (type.IsArray)
        {
            return ToArrayType(MapType(type.GetElementType()!, nullability?.ElementType));
        }

        if (type.IsGenericType)
        {
            var arguments = type.GetGenericArguments();

            if (arguments.Length == 2
                && IsEnumerableOf(type, typeof(KeyValuePair<,>).MakeGenericType(arguments)))
            {
                return $"Record<string, {MapType(arguments[1], GetGenericArgument(nullability, 1))}>";
            }

            if (arguments.Length == 1 && IsEnumerableOf(type, arguments[0]))
            {
                return ToArrayType(MapType(arguments[0], GetGenericArgument(nullability, 0)));
            }

            return MapUnsupportedType(type);
        }

        if (typeof(Delegate).IsAssignableFrom(type)
            || type.IsInterface
            || type.IsAbstract
            || type.IsPrimitive
            || type.IsPointer
            || type.IsByRef)
        {
            return MapUnsupportedType(type);
        }

        var enumerable = type.GetInterfaces()
            .FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IEnumerable<>));
        if (enumerable is not null)
        {
            return ToArrayType(MapType(enumerable.GetGenericArguments()[0], null));
        }

        return DeclareType(type);
    }

    private string MapUnsupportedType(Type type)
    {
        AddWarning($"{type} has no TypeScript mapping; it is declared as unknown.");
        return "unknown";
    }

    private string DeclareType(Type type)
    {
        if (_typeNames.TryGetValue(type, out var name))
        {
            return name;
        }

        name = ReserveName(ToIdentifier(type.Name));
        _typeNames[type] = name;
        _pendingTypes.Enqueue(type);
        return name;
    }

    private string ReserveName(string name)
    {
        var candidate = name;
        for (var i = 2; !_usedNames.Add(candidate); i++)
        {
            candidate = $"{name}{i}";
        }

        return candidate;
    }

    private void AddWarning(string warning)
    {
        if (!_warnings.Contains(warning))
        {
            _warnings.Add(warning);
        }
    }

    private static NullabilityInfo? GetGenericArgument(NullabilityInfo? nullability, int index)
    {
        return nullability is not null && nullability.GenericTypeArguments.Length > index
            ? nullability.GenericTypeArguments[index]
            : null;
    }

    private static bool IsEnumerableOf(Type type, Type elementType)
    {
        return typeof(IEnumerable<>).MakeGenericType(elementType).IsAssignableFrom(type);
    }

    private static string ToArrayType(string elementType)
    {
        return elementType.Contains(' ') ? $"({elementType})[]" : $"{elementType}[]";
    }

    private static string ToCamelCase(string name)
    {
        return JsonNamingPolicy.CamelCase.ConvertName(name);
    }

    private static string ToIdentifier(string name)
    {
        var builder = new StringBuilder(name.Length);
        foreach (var c in name)
        {
            builder.Append(char.IsAsciiLetterOrDigit(c) || c is '_' or '$' ? c : '_');
        }

        if (builder.Length == 0 || char.IsAsciiDigit(builder[0]))
        {
            builder.Insert(0, '_');
        }

        return builder.ToString();
    }

    private static string ToPropertyKey(string name)
    {
        return ToIdentifier(name) == name ? name : JsonSerializer.Serialize(name);
    }

    private static IEnumerable<Type> GetLoadableTypes(Assembly assembly)
    {
        try
        {
            return assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException e)
        {
            return e.Types.OfType<Type>();
        }
    }
}
