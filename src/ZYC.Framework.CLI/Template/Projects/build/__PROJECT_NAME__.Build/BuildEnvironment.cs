using System.Text.RegularExpressions;
using ZYC.CoreToolkit;

namespace __PROJECT_NAME__.Build;

public static class BuildEnvironment
{
    public static string BuildVersion => "0.0.1";

    public static string RootFolder => ProjectTools.GetSlnxFolderPath()!;

    public static string OutputPath => Path.Combine(RootFolder, "_bin");

    public static string TempSlnFile => Path.Combine(RootFolder, "_temp.sln");

    public static string BuildProjectPath => Path.Combine(RootFolder, "__PROJECT_NAME__.Build");

    public static string VersionPropsPath => Path.Combine(RootFolder, "version.props");


    public static string ReadVersionFromNuGetProps(string propsFile, string propertyName)
    {
        var content = File.ReadAllText(propsFile);
        var regex = new Regex(
            $"(?s)<{Regex.Escape(propertyName)}>\\s*([^<]+?)\\s*</{Regex.Escape(propertyName)}>");
        var result = regex.Match(content).Groups[1].Value.Trim();
        if (string.IsNullOrWhiteSpace(result))
        {
            throw new InvalidOperationException(
                $"Cannot find '{propertyName}' in '{propsFile}'.");
        }

        return result;
    }

    public static void UpdateVersionProps()
    {
        var props =
            "<!--!WARNING Automatically generated by __PROJECT_NAME__.Build, do not modify manually...-->\r\n" +
            "<Project>\r\n" +
            "  <PropertyGroup>\r\n" +
            $"    <Version>{BuildVersion}</Version>\r\n" +
            "  </PropertyGroup>\r\n" +
            "</Project>";

        File.WriteAllText(VersionPropsPath, props, new System.Text.UTF8Encoding(true));
    }

    public static string[] GetCsprojFilePaths(string projectRootFolder)
    {
        var allCsprojFiles = IOTools.GetAllCsprojFiles(projectRootFolder);

        var result = new List<string>();

        foreach (var file in allCsprojFiles)
        {
            var content = File.ReadAllText(file);
            if (content.Contains("<IgnoreFromPublish>true</IgnoreFromPublish>"))
            {
                continue;
            }

            result.Add(file);
        }

        return result.ToArray();
    }
}
