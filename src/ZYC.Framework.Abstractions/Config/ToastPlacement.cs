namespace ZYC.Framework.Abstractions.Config;

/// <summary>
///     Specifies the corner where toast notifications are displayed.
/// </summary>
public enum ToastPlacement
{
    /// <summary>
    ///     Displays toast notifications in the bottom-right corner.
    /// </summary>
    BottomRight = 0,

    /// <summary>
    ///     Displays toast notifications in the top-left corner.
    /// </summary>
    TopLeft = 1,

    /// <summary>
    ///     Displays toast notifications in the top-right corner.
    /// </summary>
    TopRight = 2,

    /// <summary>
    ///     Displays toast notifications in the bottom-left corner.
    /// </summary>
    BottomLeft = 3
}
